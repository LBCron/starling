"""Kev-0.8B CUDA graph spike (issue #140, ask 1): load, placement and latency of ONNX graphs in the Corvid S1 shape.

Subcommands:
  load       Try to create a session on a graph and, if that works, run a state pass and a multi-token row from its
             cache. Prints the exact error of the first step that fails. Never raises.
  placement  Session profiling of one state pass and two cached rows: nodes per provider, CPU-side nodes by op and
             kernel time per provider.
  present    Where every `present.*` output of a state pass lives: read with `OrtValue.device_name()` after a plain run
             and after binding the outputs to the device.
  bench      Latency of `Decide`'s layout: one state pass, then each question as a row from the state's cache.

`bench --cache host` keeps the cache in host memory, which is what `KevDecisionModel` does: plain `Run`, outputs in
host memory, fed back for each row. `bench --cache device` uses I/O binding: the state pass writes `present.*` to the
device and every row reads them there. Neither is the .NET path itself; this is Python ONNX Runtime on the same native
version.

Tokens come from the Kev fixtures generated by model-pipeline/reference/kev/kev_fixtures.py. The state is the first 600
tokens of a 2k document state. The branches are real question branches of other records, chosen to span S1's branch
length range, so the answers mean nothing and only latency and agreement between graphs are read from them.

Run with the environment of the Kev spike (onnxruntime-gpu 1.30.0) and CUDA_DEVICE_ORDER=PCI_BUS_ID
CUDA_VISIBLE_DEVICES=1. See README.md for the commands.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import tempfile
import threading
import time
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
import onnxruntime as ort
from safetensors.numpy import load_file

ORT_TYPES = {"tensor(float)": np.float32, "tensor(float16)": np.float16, "tensor(int64)": np.int64}
KV_DIM = 256
BRANCH_LENGTHS = [17, 33, 62, 83, 36, 50, 100, 112]  # the first four are the 4-question set (S1: 17-83 tokens)


def make_session(path: Path, profile_prefix: str | None = None, log_severity: int | None = None):
    ort.preload_dlls()
    opts = ort.SessionOptions()
    if profile_prefix:
        opts.enable_profiling = True
        opts.profile_file_prefix = profile_prefix
    if log_severity is not None:
        opts.log_severity_level = log_severity
    providers = [("CUDAExecutionProvider", {"device_id": 0, "use_tf32": "0"}), "CPUExecutionProvider"]
    return ort.InferenceSession(str(path), opts, providers=providers)


class Head:
    """The pointer head, as kev_ort.Head."""

    def __init__(self, directory: Path):
        w = load_file(str(directory / "head.safetensors"))
        meta = json.loads((directory / "head.json").read_text(encoding="utf-8"))
        self.qw, self.qb, self.kw, self.kb = w["q.weight"], w["q.bias"], w["k.weight"], w["k.bias"]
        self.scale = np.float32(1 / np.sqrt(meta["head_dim"]))
        self.temperature = np.float32(meta["temperature"])

    def probs(self, selected: np.ndarray) -> np.ndarray:
        q = selected[0] @ self.qw.T + self.qb
        k = selected[1:] @ self.kw.T + self.kb
        z = (k @ q) * self.scale / self.temperature
        e = np.exp(z - z.max())
        return e / e.sum()


def load_tokens(fixtures: Path, long_fixture: Path, state_tokens: int) -> tuple[np.ndarray, list[dict]]:
    with np.load(long_fixture) as z:
        state = z["state_ids"][:state_tokens].astype(np.int64)
    branches = []
    for path in sorted(fixtures.glob("r*.npz")):
        with np.load(path) as z:
            for key in z.files:
                if key.endswith("_readout"):
                    q = key[: -len("_readout")]
                    branches.append({"ids": z[f"{q}_ids"].astype(np.int64), "readout": z[key].astype(np.int64)})
    chosen = []
    for target in BRANCH_LENGTHS:
        best = min(range(len(branches)), key=lambda i: abs(len(branches[i]["ids"]) - target))
        chosen.append(branches.pop(best))
    return state, chosen


class Graph:
    def __init__(self, session):
        self.session = session
        self.inputs = {i.name: i for i in session.get_inputs()}
        self.outputs = [o.name for o in session.get_outputs()]
        self.past = [n for n in self.inputs if n.startswith("past")]
        self.present = [n.replace("past_key_values", "present").replace("past", "present", 1) for n in self.past]
        self.hidden = next(o for o in self.outputs if "hidden" in o)
        self.empty = {}
        for name in self.past:
            meta = self.inputs[name]
            shape = []
            for i, d in enumerate(meta.shape):
                if isinstance(d, int):
                    shape.append(d)
                elif i == 0:
                    shape.append(1)
                elif d == "kv_cache_dim":
                    shape.append(KV_DIM)
                else:
                    shape.append(0)
            self.empty[name] = np.zeros(shape, dtype=ORT_TYPES[meta.type])

    def scalars(self, ids: np.ndarray, past_length: int) -> dict[str, np.ndarray]:
        n = len(ids)
        feed = {
            "input_ids": ids[None],
            "attention_mask": np.ones((1, past_length + n), dtype=np.int64),
        }
        if "position_ids" in self.inputs:
            pos = np.arange(past_length, past_length + n, dtype=np.int64)[None]
            rank = len(self.inputs["position_ids"].shape)
            feed["position_ids"] = np.broadcast_to(pos, (3, *pos.shape)).copy() if rank == 3 else pos
        return feed

    # The host path, as KevDecisionModel.RunState and RunRows.
    def state_host(self, ids: np.ndarray) -> dict[str, np.ndarray]:
        out = self.session.run(self.present, {**self.scalars(ids, 0), **self.empty})
        return dict(zip(self.past, out, strict=True))

    def row_host(self, ids: np.ndarray, past_length: int, past: dict) -> np.ndarray:
        return self.session.run([self.hidden], {**self.scalars(ids, past_length), **past})[0]

    # The device path: present.* bound to the device on the state pass, fed back as device OrtValues.
    def state_device(self, ids: np.ndarray) -> dict:
        io = self.session.io_binding()
        for name, value in self.scalars(ids, 0).items():
            io.bind_ortvalue_input(name, ort.OrtValue.ortvalue_from_numpy(value))
        for name, value in self.empty.items():
            io.bind_ortvalue_input(name, ort.OrtValue.ortvalue_from_numpy(value))
        for name in self.present:
            io.bind_output(name, "cuda", 0)
        self.session.run_with_iobinding(io)
        values = io.get_outputs()
        # Names follow the binding order of the outputs.
        return {"io": io, "values": dict(zip(self.past, [values[i] for i in range(len(self.past))], strict=True))}

    def row_device(self, ids: np.ndarray, past_length: int, cache: dict) -> np.ndarray:
        io = self.session.io_binding()
        for name, value in self.scalars(ids, past_length).items():
            io.bind_ortvalue_input(name, ort.OrtValue.ortvalue_from_numpy(value))
        for name, value in cache["values"].items():
            io.bind_ortvalue_input(name, value if isinstance(value, ort.OrtValue) else ort.OrtValue(value))
        io.bind_output(self.hidden, "cpu", 0)
        self.session.run_with_iobinding(io)
        return io.copy_outputs_to_cpu()[0]


def cmd_load(args) -> dict:
    result = {"graph": str(args.onnx), "steps": []}

    def step(name, fn):
        try:
            value = fn()
            result["steps"].append({"step": name, "ok": True})
            return value
        except Exception as e:  # noqa: BLE001 - the error text is the result
            result["steps"].append({"step": name, "ok": False, "error": str(e).strip()[:600]})
            return None

    session = step("create session (CUDA EP, use_tf32=0)", lambda: make_session(args.onnx))
    if session is None:
        return result
    graph = Graph(session)
    state = np.arange(1000, 1000 + args.state_tokens, dtype=np.int64)
    branch = np.arange(2000, 2000 + args.branch_tokens, dtype=np.int64)
    past = step(f"state pass, {len(state)} tokens, empty cache", lambda: graph.state_host(state))
    if past is None:
        return result
    step(
        f"row of {len(branch)} tokens from the cached state",
        lambda: graph.row_host(branch, len(state), past),
    )
    return result


def cmd_placement(args) -> dict:
    prefix = os.path.join(tempfile.gettempdir(), args.out.stem + "-profile")
    session = make_session(args.onnx, profile_prefix=prefix, log_severity=args.log_severity)
    graph = Graph(session)
    state, branches = load_tokens(args.fixtures, args.long_fixture, args.state_tokens)
    past = graph.state_host(state)
    for _ in range(2):
        graph.row_host(branches[3]["ids"], len(state), past)
    profile = Path(session.end_profiling())
    events = json.loads(profile.read_text(encoding="utf-8"))
    profile.unlink()
    nodes, kernel_us = {}, defaultdict(int)
    op_us = Counter()
    for ev in events:
        a = ev.get("args", {})
        if ev.get("cat") == "Node" and "provider" in a and ev["name"].endswith("_kernel_time"):
            nodes[ev["name"][: -len("_kernel_time")]] = (a.get("op_name"), a["provider"])
            kernel_us[a["provider"]] += ev["dur"]
            op_us[f"{a.get('op_name')} on {a['provider']}"] += ev["dur"]
    return {
        "graph": str(args.onnx),
        "session_providers": session.get_providers(),
        "provider_options_use_tf32": session.get_provider_options()["CUDAExecutionProvider"]["use_tf32"],
        "nodes_profiled": len(nodes),
        "nodes_by_provider": dict(Counter(p for _, p in nodes.values())),
        "cpu_nodes_by_op": dict(
            Counter(op for op, p in nodes.values() if p == "CPUExecutionProvider").most_common()
        ),
        "attention_ops": dict(
            Counter(
                f"{op} on {p}"
                for op, p in nodes.values()
                if op in {"GroupQueryAttention", "MultiHeadAttention", "LinearAttention"}
            )
        ),
        "kernel_ms_per_provider_state_pass_plus_2_rows": {k: v / 1000 for k, v in kernel_us.items()},
        "top_ops_ms": {k: v / 1000 for k, v in op_us.most_common(8)},
        "cache_bytes_600_tokens": int(sum(v.nbytes for v in past.values())),
        "state_tokens": len(state),
        "row_tokens": len(branches[3]["ids"]),
    }


def cmd_present(args) -> dict:
    session = make_session(args.onnx)
    graph = Graph(session)
    state, _ = load_tokens(args.fixtures, args.long_fixture, args.state_tokens)
    # `session.run` returns numpy, which says nothing about the device, so the plain run keeps OrtValues. No output is
    # preallocated, as with a plain `Run`, and ONNX Runtime picks where the fetched value lives.
    feed = {**graph.scalars(state, 0), **graph.empty}
    plain = session.run_with_ort_values(
        graph.present, {name: ort.OrtValue.ortvalue_from_numpy(value) for name, value in feed.items()}
    )
    bound = graph.state_device(state)["values"]
    return {
        "graph": str(args.onnx),
        "state_tokens": len(state),
        "present_outputs": len(graph.present),
        "plain_run_devices": dict(Counter(v.device_name() for v in plain)),
        "bound_devices": dict(Counter(v.device_name() for v in bound.values())),
    }


class GpuSampler:
    """Utilization of the card and device memory of this process, from nvidia-smi."""

    def __init__(self, index: str, period: float = 0.25):
        self.index, self.period = index, period
        self.util, self.memory, self._stop = [], 0.0, threading.Event()
        self._thread = threading.Thread(target=self._loop, daemon=True)

    def _loop(self):
        while not self._stop.is_set():
            q = ["nvidia-smi", "-i", self.index, "--query-gpu=utilization.gpu", "--format=csv,noheader,nounits"]
            out = subprocess.run(q, capture_output=True, text=True, check=False).stdout.strip()
            if out.isdigit():
                self.util.append(int(out))
            q = ["nvidia-smi", "-i", self.index, "--query-compute-apps=pid,used_memory", "--format=csv,noheader,nounits"]
            out = subprocess.run(q, capture_output=True, text=True, check=False).stdout
            for line in out.splitlines():
                pid, mb = line.split(", ")
                if int(pid) == os.getpid():
                    self.memory = max(self.memory, float(mb))
            self._stop.wait(self.period)

    def __enter__(self):
        self._thread.start()
        return self

    def __exit__(self, *_):
        self._stop.set()
        self._thread.join()


def percentile(values: list[float], q: float) -> float:
    """Nearest rank, as S1 reports."""
    a = sorted(values)
    return a[min(len(a) - 1, int(np.ceil(q * len(a))) - 1)]


def summary(values: list[float]) -> dict:
    return {
        "n": len(values),
        "p50": round(percentile(values, 0.5), 2),
        "p90": round(percentile(values, 0.9), 2),
        "p99": round(percentile(values, 0.99), 2),
        "mean": round(float(np.mean(values)), 2),
        "min": round(min(values), 2),
    }


def cmd_bench(args) -> dict:
    t0 = time.perf_counter()
    graph = Graph(make_session(args.onnx))
    load_s = time.perf_counter() - t0
    head = Head(args.head)
    state, branches = load_tokens(args.fixtures, args.long_fixture, args.state_tokens)
    branches = branches[: args.questions]

    def call() -> tuple[float, float, list[np.ndarray]]:
        start = time.perf_counter()
        if args.cache == "host":
            cache = graph.state_host(state)
            run = graph.row_host
        else:
            cache = graph.state_device(state)
            run = graph.row_device
        after_state = time.perf_counter()
        answers = []
        for b in branches:
            hidden = run(b["ids"], len(state), cache)
            answers.append(head.probs(hidden[0, b["readout"]].astype(np.float32)))
        end = time.perf_counter()
        return (after_state - start) * 1e3, (end - after_state) * 1e3, answers

    for _ in range(args.warmup):
        call()
    totals, states, rows, answers = [], [], [], None
    load_before = os.getloadavg()[0]
    with GpuSampler(args.gpu_index) as gpu:
        for _ in range(args.calls):
            s, r, answers = call()
            states.append(s)
            rows.append(r)
            totals.append(s + r)
    return {
        "graph": str(args.onnx),
        "cache": args.cache,
        "label": args.label,
        "state_tokens": len(state),
        "branch_tokens": [len(b["ids"]) for b in branches],
        "warmup": args.warmup,
        "load_seconds": round(load_s, 2),
        "total_ms": summary(totals),
        "state_pass_ms": summary(states),
        "rows_ms": summary(rows),
        "gpu_utilization_percent_mean": round(float(np.mean(gpu.util)), 1) if gpu.util else None,
        "gpu_samples": len(gpu.util),
        "process_gpu_memory_mib_peak": gpu.memory,
        "load_average_1m_before": round(load_before, 2),
        "load_average_1m_after": round(os.getloadavg()[0], 2),
        "probabilities": [a.tolist() for a in answers],
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["load", "placement", "present", "bench"])
    parser.add_argument("--onnx", type=Path, required=True)
    parser.add_argument("--head", type=Path)
    parser.add_argument("--fixtures", type=Path)
    parser.add_argument("--long-fixture", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--label", default="")
    parser.add_argument("--cache", choices=["host", "device"], default="host")
    parser.add_argument("--state-tokens", type=int, default=600)
    parser.add_argument("--branch-tokens", type=int, default=40)
    parser.add_argument("--questions", type=int, default=4)
    parser.add_argument("--calls", type=int, default=100)
    parser.add_argument("--warmup", type=int, default=10)
    parser.add_argument("--gpu-index", default="1", help="nvidia-smi index of the card, for sampling only")
    parser.add_argument("--log-severity", type=int, default=1)
    args = parser.parse_args()
    result = {"load": cmd_load, "placement": cmd_placement, "present": cmd_present, "bench": cmd_bench}[args.command](args)
    result["onnxruntime"] = ort.__version__
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in result.items() if k != "probabilities"}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
